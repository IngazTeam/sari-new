CREATE TABLE `ai_sales_experiment_generations` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `merchant_id` int NOT NULL,
  `turn_id` bigint unsigned NOT NULL,
  `actor_user_id` int DEFAULT NULL,
  `request_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `payload_digest` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `authorization_digest` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `snapshot` json NOT NULL,
  `state` enum('dispatching','responded','invalid','blocked','uncertain') NOT NULL,
  `claim_token` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `reservation_key` varchar(64) DEFAULT NULL,
  `response_text` mediumtext,
  `response_metadata` json DEFAULT NULL,
  `response_digest` char(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `failure_code` varchar(64) DEFAULT NULL,
  `lease_until` datetime(3) DEFAULT NULL,
  `completed_at` datetime(3) DEFAULT NULL,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_sales_generation_request` (`merchant_id`,`request_id`),
  UNIQUE KEY `uq_sales_generation_turn` (`merchant_id`,`turn_id`),
  UNIQUE KEY `uq_sales_generation_reservation` (`reservation_key`),
  CONSTRAINT `fk_sales_generation_merchant` FOREIGN KEY (`merchant_id`) REFERENCES `merchants` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_sales_generation_turn` FOREIGN KEY (`turn_id`) REFERENCES `ai_sales_experiment_turns` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_sales_generation_actor` FOREIGN KEY (`actor_user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL
);
